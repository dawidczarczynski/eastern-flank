#!/usr/bin/env python3
"""Generates docs/CODEMAP.md: one line per GDScript file under src/ (class name and the first `##` doc line).

Agents Grep it to find where things live instead of exploring the tree. Run by tools/check.sh, which keeps the
committed file current; run it by hand after adding classes.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CODEMAP.md"
CLASS = re.compile(r"^class_name (\w+)")
DOC = re.compile(r"^## ?(.*)")
MAX_DOC = 90


def describe(path: Path) -> str:
	name = None
	doc = ""
	for line in path.read_text(encoding="utf-8").splitlines()[:40]:
		match = CLASS.match(line)
		if match:
			name = match.group(1)
		doc_match = DOC.match(line)
		if doc_match and not doc:
			doc = doc_match.group(1).strip()
	doc = doc if len(doc) <= MAX_DOC else doc[: MAX_DOC - 1].rstrip() + "…"
	label = name or path.stem
	return f"- `{label}` – {doc}" if doc else f"- `{label}`"


def build() -> str:
	lines = [
		"# Code map",
		"",
		"Generated by `tools/codemap.py` (do not edit): one line per file under `src/`, grouped by directory.",
		"Grep it (`class name`, a keyword) instead of exploring the tree; open the file for details.",
	]
	by_dir: dict[str, list[Path]] = {}
	for path in sorted((ROOT / "src").rglob("*.gd")):
		by_dir.setdefault(str(path.parent.relative_to(ROOT)), []).append(path)
	for directory, files in by_dir.items():
		lines += ["", f"## {directory}/", ""]
		lines += [describe(path) + f" (`{path.name}`)" for path in files]
	return "\n".join(lines) + "\n"


def main() -> int:
	text = build()
	if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
		OUT.write_text(text, encoding="utf-8")
		print(f"updated {OUT.relative_to(ROOT)}")
	return 0


if __name__ == "__main__":
	raise SystemExit(main())
