#!/usr/bin/env bash
# Re-renders the two stills behind the main menu (docs/design/operational_map/main_menu.html, variant A):
#   assets/menu/staff_map.png  – the staff map without any HUD (Russian side to move, marches planned)
#   assets/menu/battle.png     – the tactical battle: the Homar-K salvo of the teaser (tools/teaser.sh --still)
# Both are 1792x1008 GPU renders (HIGH quality, same requirements as tools/screenshot.sh; under WSL the
# Windows Godot build). Run by tools/readme_screenshot.sh, i.e. after every visible change to the battle
# or the staff map (CLAUDE.md "When a task is done", step 5) – commit the PNGs with the change.
# Usage: tools/menu_backdrop.sh [--only=map|battle]
#   The battle still records the film up to BATTLE_SECONDS (default 5.8 s after the salvo start) as a PNG
#   sequence: it takes a few minutes. The framing lives here (SCREENSHOT_STAFF_MAP, BATTLE_SECONDS).
set -uo pipefail
project_dir="$(cd "$(dirname "$0")/.." && pwd)"
cd "$project_dir"
only=""
for arg in "$@"; do
	case "$arg" in
	--only=*) only="${arg#*=}" ;;
	*) echo "Usage: tools/menu_backdrop.sh [--only=map|battle]" >&2; exit 2 ;;
	esac
done
size="1792x1008"
mkdir -p assets/menu

if [[ -z "$only" || "$only" == "map" ]]; then
	SCREENSHOT_RESOLUTION="$size" SCREENSHOT_SCENE=staff_map \
		SCREENSHOT_STAFF_MAP="${SCREENSHOT_STAFF_MAP:-side:1,zoom:1.5,focus:44:47,order:ru_tank_2:41:52:1,order:ru_mlrs_2:50:48:1,order:ru_mr_5:43:44:1,nohud}" \
		tools/screenshot.sh "$project_dir/assets/menu/staff_map.png" --frames=30 || exit $?
fi
if [[ -z "$only" || "$only" == "battle" ]]; then
	tools/teaser.sh "$project_dir/assets/menu/battle.png" --still="${BATTLE_SECONDS:-5.8}" \
		--resolution="$size" --fps=30 || exit $?
fi
# New PNGs need their *.import files (generated by Godot; commit them with the images).
GODOT="${GODOT:-godot}"
[[ -x "$HOME/.local/bin/godot" ]] && ! command -v "$GODOT" >/dev/null 2>&1 && GODOT="$HOME/.local/bin/godot"
timeout 120 "$GODOT" --headless --path . --import >/dev/null 2>&1
echo "Main menu backdrops: assets/menu/staff_map.png, assets/menu/battle.png"
